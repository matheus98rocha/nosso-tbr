export type ReadingAvatarSeed = (typeof AVATAR_CATALOG)[number]["seed"];

const catalogSeedSet = new Set<string>(AVATAR_CATALOG.map((entry) => entry.seed));

const catalogEntryBySeed = new Map(
  AVATAR_CATALOG.map((entry) => [entry.seed, entry]),
);

export const READING_AVATAR_SEEDS = AVATAR_CATALOG.map((entry) => entry.seed);

export function getAvatarCatalogEntry(seed: string) {
  return catalogEntryBySeed.get(seed);
}

export function isReadingAvatarSeed(
  value: string | null | undefined,
): value is ReadingAvatarSeed {
  if (!value) {
    return false;
  }

  return catalogSeedSet.has(value);
}

export function isStoredAvatarSeed(
  value: string | null | undefined,
): value is string {
  return typeof value === "string" && value.trim().length > 0;
}
